import type { SparkOrigin } from "@/lib/types";

const BADGE: Record<SparkOrigin, { label: string; title: string; className: string }> = {
  demo: {
    label: "◆ Demo",
    title: "Placeholder content—not generated and not researched",
    className: "border-demo text-demo",
  },
  "ai-hypothesis": {
    label: "◇ Hypothesis",
    title: "Generated by Claude from general knowledge—not verified against live data",
    className: "border-hypo text-hypo",
  },
};

/** Proof-stamp label saying where a piece of content came from. */
export function OriginBadge({ origin }: { origin: SparkOrigin }) {
  const badge = BADGE[origin];
  return (
    <span
      className={`readout inline-flex items-center gap-1 rounded-sm border border-dashed px-1.5 py-px text-[10px] font-bold ${badge.className}`}
      title={badge.title}
    >
      {badge.label}
    </span>
  );
}

/** Shorthand for placeholder content. */
export function DemoBadge({ show = true }: { show?: boolean }) {
  return show ? <OriginBadge origin="demo" /> : null;
}
