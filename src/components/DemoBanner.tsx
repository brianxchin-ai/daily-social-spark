"use client";

import { useEngineStatus } from "@/lib/use-engine-status";

/** Persistent notice naming which engine produces results, and what that means. */
export function DemoBanner() {
  const status = useEngineStatus();

  if (status?.engine === "claude") {
    return (
      <div role="note" className="readout w-full bg-hypo px-4 py-2 text-center text-[11px] text-surface">
        <span className="font-bold">◇ AI hypotheses</span>
        <span className="mx-2 opacity-60">/</span>
        <span className="sm:hidden">Not verified live trends</span>
        <span className="hidden sm:inline">
          Generated by Claude from general knowledge
          <span className="mx-2 opacity-60">/</span>
          Not verified live trends
        </span>
      </div>
    );
  }

  if (status?.engine === "demo") {
    return (
      <div role="note" className="readout w-full bg-demo px-4 py-2 text-center text-[11px] text-surface">
        <span className="font-bold">◆ Demo mode</span>
        <span className="mx-2 opacity-60">/</span>
        <span className="sm:hidden">All content is placeholder</span>
        <span className="hidden sm:inline">
          Trends, sources, metrics &amp; recommendations are placeholder
          <span className="mx-2 opacity-60">/</span>
          Live research not connected
        </span>
      </div>
    );
  }

  return (
    <div role="note" className="readout w-full bg-ink-soft px-4 py-2 text-center text-[11px] text-surface">
      Checking which engine is active…
    </div>
  );
}
